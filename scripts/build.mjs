import { appendFile, mkdir, readFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { join } from 'node:path';
import assert from 'node:assert/strict';
import { npmCommand } from './npm-command.mjs';
await mkdir('release', { recursive: true });
const invocation = npmCommand(['pack', '--ignore-scripts', '--json', '--pack-destination', 'release']);
const packed = spawnSync(invocation.command, invocation.args, { encoding: 'utf8', timeout: 120000 });
assert.equal(packed.status, 0, packed.stderr);
const parsed = JSON.parse(packed.stdout);
const packages = Array.isArray(parsed) ? parsed : Object.values(parsed);
const manifest = JSON.parse(await readFile('package.json', 'utf8'));
assert.equal(packages.length, 1, 'Build must produce exactly one package.');
assert.equal(packages[0].name, manifest.name);
assert.equal(packages[0].version, manifest.version);
const filename = packages[0].filename;
assert(/^[A-Za-z0-9._-]+\.tgz$/.test(filename), 'Unexpected package archive filename.');
const archive = join('release', filename);
const smoke = spawnSync(process.execPath, ['scripts/package-smoke.mjs', '--tarball', archive, ...process.argv.slice(2)], { stdio: 'inherit', timeout: 180000 });
assert.equal(smoke.status, 0, 'Installed-consumer package verification failed.');
if (process.env.GITHUB_OUTPUT) await appendFile(process.env.GITHUB_OUTPUT, `archive=release/${filename}\n`);
console.log(`Verified ${manifest.name}@${manifest.version}: ${archive}`);
